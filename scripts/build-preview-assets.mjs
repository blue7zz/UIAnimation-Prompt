import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFile(path.join(root, file), 'utf8');
const assets = {
  css: (await read('styles/motion-tokens.css')) + '\n' + (await read('demos/shared/demo.css')),
  runtime: await read('demos/shared/runtime.js'),
  components: await read('demos/shared/components.js')
};
await writeFile(path.join(root, 'data/preview-assets.js'), '// Generated by node scripts/build-preview-assets.mjs; edit the shared source files instead.\nwindow.MotionPreviewAssets = ' + JSON.stringify(assets, null, 2) + ';\n');
console.log('Updated local-file preview asset cache.');
